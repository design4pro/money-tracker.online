#!/bin/sh
# om-prepare-test-env: generated entrypoint (contract v2)
# regenerate with: om-prepare-test-env --regenerate
# history:
#   2026-09-06 generated from scripts/agent/setup-e2e.sh and .github/actions/e2e-env/action.yml;
#              dev mode (vite dev on 127.0.0.1, first free port in 3011-3020), local D1 migrate,
#              seed through the real sign-up endpoint. Reuse ignores src/** changes because vite
#              dev hot-reloads them; drizzle/, package.json and pnpm-lock.yaml invalidate.
#   2026-09-06 reuse check: the sign-in probe sends an Origin header (Better Auth answered 403
#              without one, so every warm run restarted the server) and accepts 429.
set -eu

# --- project parameters --------------------------------------------------------
QA_DIR=.ai/qa
ENV_DESCRIPTOR="$QA_DIR/test-env.json"
CREDENTIALS_FILE="$QA_DIR/test-env.env"
BUILD_CACHE="$QA_DIR/test-env-build-cache.json"
LOCK_DIR="$QA_DIR/test-env.lock"
BOOT_LOG="$QA_DIR/test-env-boot.log"
APP_HOST=127.0.0.1
PORT_FROM=3011 # 3010 is the developer's own `pnpm dev` (vite.config.ts binds it with strictPort)
PORT_TO=3020   # playwright.config.ts refuses a base URL outside 3010-3020
HEALTH_PATH=/
HEALTH_TIMEOUT=120
STALE_INPUTS="drizzle package.json pnpm-lock.yaml" # newer than the descriptor -> restart
BUILD_INPUTS="package.json pnpm-lock.yaml src/routes"
BUILD_ENV_VARS=""
ARTIFACTS="node_modules/.modules.yaml src/routeTree.gen.ts"
TTL=${TEST_ENV_CACHE_TTL_SECONDS:-1800}
DEMO_EMAIL=demo@money-tracker.online
DEV_VARS_MARKER="# agent throwaway - regenerated by .ai/scripts/test-env-up.sh"

FORCE=0
FORCE_REBUILD=0
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    --force-rebuild) FORCE_REBUILD=1 ;;
    *) echo "test-env-up: unknown flag $arg" >&2; exit 2 ;;
  esac
done

cd "$(dirname "$0")/../.."
mkdir -p "$QA_DIR"

json_field() { sed -n "s/.*\"$1\": *\"\{0,1\}\([^\",}]*\)\"\{0,1\}.*/\1/p" "$2" 2>/dev/null | head -1 | sed "s/[[:space:]]*$//"; }
now_epoch() { date -u +%s; }
listening() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }
probe() { curl -fsS -o /dev/null --max-time "${2:-5}" "$1"; }

# --- lock: one bootstrap at a time ----------------------------------------------
LOCKED=0
release_lock() { [ "$LOCKED" = 1 ] && rm -rf "$LOCK_DIR"; }
trap release_lock EXIT
tries=0
while ! mkdir "$LOCK_DIR" 2>/dev/null; do
  owner=$(json_field pid "$LOCK_DIR/owner.json")
  if [ -z "$owner" ] || ! kill -0 "$owner" 2>/dev/null; then
    rm -rf "$LOCK_DIR"
    continue
  fi
  tries=$((tries + 1))
  if [ "$tries" -ge 60 ]; then
    echo "test-env-up: lock $LOCK_DIR held by pid $owner for 5 minutes" >&2
    exit 1
  fi
  sleep 5
done
LOCKED=1
printf '{ "pid": %s, "source": "%s", "acquiredAt": "%s" }\n' "$$" "$0" "$(date -u +%FT%TZ)" > "$LOCK_DIR/owner.json"

# --- reuse check: attach, do not reboot ----------------------------------------
report() {
  echo "TEST_ENV_STATUS=running"
  echo "TEST_ENV_BASE_URL=$1"
  echo "TEST_ENV_DESCRIPTOR=$ENV_DESCRIPTOR"
  echo "TEST_ENV_REUSED=$2"
  echo "BROWSER_PROVIDER=playwright"
  echo "BROWSER_INSTALLED=$3"
}

probe_auth() {
  # The password value stays inside this process: sourced, expanded by the shell, piped to curl.
  set -a
  # shellcheck disable=SC1090
  . "$CREDENTIALS_FILE"
  set +a
  # Better Auth's CSRF check needs an Origin header (403 without one, like scripts/seed/seed.mjs
  # sends). 429 means the sign-in limiter is busy, not that the credential broke: treat it as alive.
  code=$(printf '{"email":"%s","password":"%s"}' "$DEMO_EMAIL" "${TEST_OWNER_PASSWORD:-}" |
    curl -sS -o /dev/null -w '%{http_code}' --max-time 10 -H 'content-type: application/json' -H "origin: $1" \
      -d @- "$1/api/auth/sign-in/email") || return 1
  [ "$code" = 200 ] || [ "$code" = 429 ]
}

stop_recorded() {
  pid=$(json_field pid "$ENV_DESCRIPTOR")
  if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
    pkill -TERM -P "$pid" 2>/dev/null || true
    kill -TERM "$pid" 2>/dev/null || true
    sleep 2
  fi
}

if [ -f "$ENV_DESCRIPTOR" ] && [ "$(json_field status "$ENV_DESCRIPTOR")" = running ]; then
  PID=$(json_field pid "$ENV_DESCRIPTOR")
  BASE_URL=$(json_field baseUrl "$ENV_DESCRIPTOR")
  STARTED=$(json_field startedAtEpoch "$ENV_DESCRIPTOR")
  fresh=1
  [ "$FORCE" = 1 ] && fresh=0
  [ -n "$PID" ] && kill -0 "$PID" 2>/dev/null || fresh=0
  [ "$fresh" = 1 ] && { probe "$BASE_URL$HEALTH_PATH" || fresh=0; }
  [ "$fresh" = 1 ] && { probe "$BASE_URL/api/health" || fresh=0; }
  [ "$fresh" = 1 ] && [ -f "$CREDENTIALS_FILE" ] && { probe_auth "$BASE_URL" || fresh=0; }
  [ "$fresh" = 1 ] && [ $(($(now_epoch) - ${STARTED:-0})) -gt "$TTL" ] && fresh=0
  # shellcheck disable=SC2086
  [ "$fresh" = 1 ] && [ -n "$(find $STALE_INPUTS -newer "$ENV_DESCRIPTOR" 2>/dev/null | head -1)" ] && fresh=0
  if [ "$fresh" = 1 ]; then
    echo "test-env-up: reusing $BASE_URL (pid $PID)"
    report "$BASE_URL" 1 "$(json_field installed "$ENV_DESCRIPTOR" | head -1 | sed 's/true/1/;s/false/0/')"
    exit 0
  fi
  echo "test-env-up: recorded environment is stale, restarting"
  stop_recorded
fi

# --- build cache: skip preparation that has not changed --------------------------
fp_file() { stat -f '%z:%m' "$1" 2>/dev/null || stat -c '%s:%Y' "$1" 2>/dev/null; }
fingerprint() {
  {
    for p in $BUILD_INPUTS; do
      if [ -d "$p" ]; then
        find "$p" -type f ! -path '*/node_modules/*' ! -path '*/.git/*'
      elif [ -f "$p" ]; then echo "$p"; fi
    done | LC_ALL=C sort | while IFS= read -r f; do printf '%s:%s\n' "$f" "$(fp_file "$f")"; done
    for v in $BUILD_ENV_VARS; do eval "printf 'env:%s=%s\n' \"$v\" \"\${$v:-}\""; done
  } | cksum | awk '{print $1"-"$2}'
}
build_needed() {
  [ "$FORCE_REBUILD" = 1 ] && return 0
  [ -f "$BUILD_CACHE" ] || return 0
  [ "$(json_field sourceFingerprint "$BUILD_CACHE")" = "$(fingerprint)" ] || return 0
  [ "$(json_field projectRoot "$BUILD_CACHE")" = "$(pwd)" ] || return 0
  for a in $ARTIFACTS; do [ -s "$a" ] || return 0; done
  return 1
}
if build_needed; then
  echo "test-env-up: preparing (install, route tree)"
  # HUSKY=0: `prepare` would otherwise rewrite core.hooksPath in the git config the worktrees share.
  HUSKY=0 pnpm install --frozen-lockfile --prefer-offline
  pnpm generate-routes
  printf '{ "builtAt": "%s", "sourceFingerprint": "%s", "projectRoot": "%s", "artifactPaths": "%s" }\n' \
    "$(date -u +%FT%TZ)" "$(fingerprint)" "$(pwd)" "$ARTIFACTS" > "$BUILD_CACHE"
else
  echo "test-env-up: preparation cached"
fi

# --- port from the automation pool ----------------------------------------------
PORT=""
p=$PORT_FROM
while [ "$p" -le "$PORT_TO" ]; do
  if ! listening "$p"; then PORT=$p; break; fi
  p=$((p + 1))
done
[ -n "$PORT" ] || { echo "test-env-up: no free port in $PORT_FROM-$PORT_TO" >&2; exit 1; }
BASE_URL="http://$APP_HOST:$PORT"

# --- .dev.vars: throwaway secrets, never over a person's file -------------------
if [ -f .dev.vars ] && ! head -1 .dev.vars | grep -qF "$DEV_VARS_MARKER"; then
  echo "test-env-up: keeping the existing .dev.vars (not written by this script)"
  if ! grep -q "^APP_URL=$BASE_URL\$" .dev.vars; then
    echo "test-env-up: WARNING its APP_URL is not $BASE_URL; auth may reject this origin" >&2
  fi
else
  # UNSUBSCRIBE_TOKEN_SECRET is fixed, not random: e2e/unsubscribe.spec.ts mints
  # tokens with the same key (and .github/actions/e2e-env writes it). A missing
  # line makes every unsubscribe URL invalid by design.
  printf '%s\nBETTER_AUTH_SECRET=%s\nAPP_URL=%s\nUNSUBSCRIBE_TOKEN_SECRET=e2e-unsubscribe-token-secret\n' "$DEV_VARS_MARKER" "$(openssl rand -base64 32)" "$BASE_URL" > .dev.vars
fi

# --- credentials file: references for consumers, demo-grade values only ----------
printf 'TEST_OWNER_PASSWORD=%s\n' "${DEMO_PASSWORD:-money-demo-2026}" > "$CREDENTIALS_FILE"
grep -qxF "$CREDENTIALS_FILE" .gitignore || echo "$CREDENTIALS_FILE" >> .gitignore

# --- database: migrations are idempotent -------------------------------------------
echo "test-env-up: local D1 migrations"
pnpm db:migrate:local

# --- app start + health wait -----------------------------------------------------------
echo "test-env-up: dev server on $BASE_URL"
START_CMD="pnpm exec vite dev --port $PORT --strictPort --host $APP_HOST"
# shellcheck disable=SC2086
nohup $START_CMD > "$BOOT_LOG" 2>&1 &
APP_PID=$!
waited=0
until probe "$BASE_URL$HEALTH_PATH" 2>/dev/null; do
  waited=$((waited + 2))
  if [ "$waited" -ge "$HEALTH_TIMEOUT" ] || ! kill -0 "$APP_PID" 2>/dev/null; then
    echo "test-env-up: dev server did not answer on $BASE_URL within ${HEALTH_TIMEOUT}s" >&2
    tail -50 "$BOOT_LOG" >&2
    exit 1
  fi
  sleep 2
done

# --- seed through the real sign-up endpoint ---------------------------------------
echo "test-env-up: seeding the demo workspace"
set -a
# shellcheck disable=SC1090
. "$CREDENTIALS_FILE"
set +a
DEMO_PASSWORD="$TEST_OWNER_PASSWORD" node scripts/seed/seed.mjs --url "$BASE_URL"
node scripts/seed/verify.mjs

# --- browser provider state --------------------------------------------------------------
if PW_VERSION=$(pnpm exec playwright --version 2>/dev/null | awk '{print $2}'); then
  BROWSER_INSTALLED=true
else
  BROWSER_INSTALLED=false
  PW_VERSION=unknown
fi

# --- descriptor + result lines -----------------------------------------------------------
RUN_ID="$(date -u +%Y%m%dT%H%M%S)-$$"
STARTED_AT="$(date -u +%FT%TZ)"
cat > "$ENV_DESCRIPTOR" <<EOF
{
  "version": 1,
  "runId": "$RUN_ID",
  "status": "running",
  "mode": "dev",
  "baseUrl": "$BASE_URL",
  "startedByThisRepo": true,
  "startScript": ".ai/scripts/test-env-up.sh",
  "stopScript": ".ai/scripts/test-env-down.sh",
  "app": { "startCommand": "$START_CMD", "port": $PORT, "healthPath": "$HEALTH_PATH", "pid": $APP_PID },
  "services": [
    { "type": "d1-local", "host": "$APP_HOST", "port": 0, "container": "", "url": ".wrangler/state/v3/d1", "env": {} }
  ],
  "credentials": [ { "role": "owner", "username": "$DEMO_EMAIL", "passwordEnv": "TEST_OWNER_PASSWORD" } ],
  "credentialsFile": "$CREDENTIALS_FILE",
  "browser": {
    "provider": "playwright",
    "installed": $BROWSER_INSTALLED,
    "command": "pnpm exec playwright",
    "version": "$PW_VERSION",
    "descriptor": ".ai/browsers/playwright.md",
    "notes": ""
  },
  "playwright": { "runner": "playwright", "installed": $BROWSER_INSTALLED, "config": "playwright.config.ts", "browsers": ["chromium"] },
  "testRunner": { "name": "playwright", "config": "playwright.config.ts" },
  "platform": "$(uname -s | tr '[:upper:]' '[:lower:]')",
  "startedAt": "$STARTED_AT",
  "startedAtEpoch": $(now_epoch),
  "notes": "vite dev serves src/** live; the seed is anchored to e2e/baseline-day.ts and the server honours x-mt-server-today under DEV. Run the committed suite with PLAYWRIGHT_BASE_URL=$BASE_URL pnpm e2e. Boot log: $BOOT_LOG."
}
EOF
report "$BASE_URL" 0 "$(echo "$BROWSER_INSTALLED" | sed 's/true/1/;s/false/0/')"
