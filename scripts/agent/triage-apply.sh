#!/usr/bin/env bash
# The only writer of a triage verdict. Reads what the triage skill left in .agent/:
#   triage.json        {"verdict": "...", "reason": "one line"}
#   triage/notes.md    the triage notes, posted as the <!-- agent-triage --> comment
#   triage/brief.md    (promoted only) a ticket/v2 body, validated like a planned ticket
# and moves the issue: promoted -> ready, needs-info -> needs-info, needs-plan -> backlog,
# needs-human | refuted | redundant -> needs-human. Never closes, never adds a run: label.
# Idempotent: the comment is upserted and a status swap already done is a no-op.
#
#   scripts/agent/triage-apply.sh [--check]
set -euo pipefail
. "$(dirname "$0")/cez-lib.sh"
HERE=$(cd "$(dirname "$0")" && pwd)

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

N=$(issue_number) || die "no issue pinned for this run (.agent/issue)"
VERDICT_FILE="$AGENT_DIR/triage.json"
NOTES="$AGENT_DIR/triage/notes.md"
BRIEF="$AGENT_DIR/triage/brief.md"

[ -s "$VERDICT_FILE" ] || die "no $VERDICT_FILE"
VERDICT=$(jq -r '.verdict // empty' "$VERDICT_FILE")
REASON=$(jq -r '.reason // empty' "$VERDICT_FILE")
case "$VERDICT" in
  promoted|needs-info|needs-plan|needs-human|refuted|redundant) ;;
  *) die "unknown verdict '${VERDICT}' in $VERDICT_FILE" ;;
esac
[ -n "$REASON" ] || die "$VERDICT_FILE needs a one-line reason"
[ -s "$NOTES" ] || die "no $NOTES; the notes are the comment a human reads"

ISSUE=$(gh_issue_json "$N" title,body,labels)
TYPE=$(jq -r '[.labels[].name | select(startswith("type: "))] | .[0] // empty' <<<"$ISSUE")
case "$VERDICT" in
  promoted)
    case "$TYPE" in
      "type: bug"|"type: enhancement"|"type: maintenance") ;;
      *) die "promoted needs type: bug, enhancement or maintenance (found ${TYPE:-none}); a feature is needs-plan" ;;
    esac
    [ -s "$BRIEF" ] || die "promoted needs $BRIEF (a ticket/v2 body)"
    node "$HERE/plan.mjs" check-body ticket/v2 "$BRIEF" || die "$BRIEF is not a valid ticket/v2 body"
    TARGET="status: ready" ;;
  needs-info) TARGET="status: needs-info" ;;
  needs-plan) TARGET="status: backlog" ;;
  *) TARGET="status: needs-human" ;;
esac

if [ "$CHECK" -eq 1 ]; then
  say "ok: $VERDICT -> $TARGET"
  exit 0
fi

if [ "$VERDICT" = "promoted" ]; then
  say "==> agent brief into the body of #$N"
  plan_body_with_original "$BRIEF" "$(jq -r '.body // ""' <<<"$ISSUE")" | neutralise \
    | gh issue edit "$N" --repo "$REPO" --body-file - > /dev/null
fi

say "==> triage notes"
{
  printf '> _This was generated by AI during triage._\n\n**Verdict:** `%s` → `%s`\n**Reason:** %s\n\n' "$VERDICT" "$TARGET" "$REASON"
  cat "$NOTES"
  if [ "$VERDICT" = "promoted" ]; then
    printf '\nPromoted automatically. Remove `status: ready` to hold this for a human decision.\n'
  else
    printf '\nAdd `run: triage` to triage again once the cause is addressed.\n'
  fi
} | comment_upsert "$N" "<!-- agent-triage -->"
swap_status "$N" "$TARGET"
say "==> #$N: $VERDICT -> $TARGET"
