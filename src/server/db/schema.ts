/**
 * The product schema for money-tracker.online (D1 / SQLite via Drizzle).
 *
 * Better Auth's own tables live in `./auth-schema.ts`. Both files are named explicitly in
 * `drizzle.config.ts`, so a table is part of the migration history whichever file it sits in.
 *
 * ---------------------------------------------------------------------------
 * CONVENTIONS — every table in this file obeys all of them
 * ---------------------------------------------------------------------------
 *
 * **Ids.** `text` primary keys minted in the application layer as base36 epoch-ms +
 * `nanoid(16)` — 25 characters, sortable by creation time, so keyset pagination runs on the
 * primary key rather than on a secondary index.
 *
 * **Money.** `integer` **minor units** plus a `text(3)` ISO-4217 code, always as a pair. The
 * scale is `currencies.digits`, **never a hard-coded 2**: the yen has no minor unit and the
 * Kuwaiti dinar has three, and a schema that assumes two is wrong for both by a factor of a
 * hundred and a thousand respectively. No column in the money path is ever a float. Rounding is
 * `roundHalfToEven`, in `src/lib/money`.
 *
 * **Rates.** `rate_e10 integer` — the rate multiplied by 10^10. A `FLOAT` rate column cannot
 * represent a repeating decimal exactly, so two systems reading the same stored rate compute
 * different converted amounts; an integer cannot drift.
 *
 * **Dates.** Calendar dates are `text` `YYYY-MM-DD`; times are `HH:MM`; instants are epoch-ms
 * `integer`. The three are never mixed in one column. **Day bucketing is UTC everywhere** — the
 * SQL truncation, the midnight walk and every `date` column — and the reader's timezone is
 * applied at render only.
 *
 * **Enums.** Every enumerated column carries a SQL `CHECK` generated by {@link enumCheck} from
 * the exported tuple that also types it, so the database and TypeScript cannot disagree about
 * what the allowed values are.
 *
 * **Indexes.** Every foreign key and every filtered or sorted column is indexed. **Every tenant
 * table carries `organization_id`, and it is the leading column of every composite index on that
 * table** — a tenant-scoped query that cannot use the index is a tenant-scoped table scan.
 *
 * ---------------------------------------------------------------------------
 * SCOPE OF THIS FILE TODAY
 * ---------------------------------------------------------------------------
 * The SaaS layer's own table (`subscriptions`, the Polar mirror) and the two global catalog
 * tables the money path reads (`currencies`, `exchange_rates`). The finance domain — accounts,
 * transactions, budgets, recurring series, rules, goals, import and export — is built on top of
 * this in a later plan; it is absent rather than sketched, because a half-declared table
 * generates a migration that has to be reverted.
 */

import { sql } from 'drizzle-orm'
import {
  check,
  index,
  integer,
  primaryKey,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core'

import type { AnySQLiteColumn } from 'drizzle-orm/sqlite-core'
import type { SQL } from 'drizzle-orm'

import { organization } from './auth-schema'

/* -------------------------------------------------------------------------- */
/* Shared column and constraint helpers                                       */
/* -------------------------------------------------------------------------- */

/** A 25-character application-minted id. See the docblock above. */
const id = () => text('id').primaryKey()

/** Epoch milliseconds. Never a SQLite `datetime` string: the two sort differently. */
const createdAt = () =>
  integer('created_at', { mode: 'timestamp_ms' }).notNull()
const updatedAt = () =>
  integer('updated_at', { mode: 'timestamp_ms' }).notNull()

/** An ISO-4217 alphabetic code. Three characters, upper case, always. */
const currencyCode = (name: string) => text(name, { length: 3 })

/**
 * A `CHECK` constraint restricting a column to one tuple of literals.
 *
 * The tuple is the same value the column's TypeScript type is derived from, so adding a variant
 * in one place and forgetting the other is impossible. Values are inlined as SQL string literals
 * rather than bound parameters because a `CHECK` is part of the table definition and cannot carry
 * placeholders; every caller in this file passes a frozen tuple of source literals, never input.
 */
function enumCheck(
  constraintName: string,
  column: AnySQLiteColumn,
  values: ReadonlyArray<string>,
): ReturnType<typeof check> {
  const list: SQL = sql.join(
    values.map((value) => sql.raw(`'${value.replaceAll("'", "''")}'`)),
    sql`, `,
  )
  return check(constraintName, sql`${column} in (${list})`)
}

/* -------------------------------------------------------------------------- */
/* Billing — the Polar mirror                                                 */
/* -------------------------------------------------------------------------- */

/**
 * Plan tiers. Mirrors `PLAN_IDS` in the isomorphic plan catalog; the column is the *cached*
 * answer and the product id is the authoritative one, which is why `resolveLimits()` reads the
 * product id first and falls back to this column second.
 */
export const PLAN_IDS = ['free', 'plus', 'household'] as const
export type PlanId = (typeof PLAN_IDS)[number]

/** How often the subscription bills. */
export const BILLING_INTERVALS = ['monthly', 'yearly'] as const
export type BillingInterval = (typeof BILLING_INTERVALS)[number]

/**
 * Subscription lifecycle, in the provider's vocabulary.
 *
 * `past_due` is dunning, not a lockout: a failed card must not take a household's ledger away
 * while the retry schedule runs. The set that actually entitles lives in the plan catalog.
 */
export const SUBSCRIPTION_STATUSES = [
  'trialing',
  'active',
  'past_due',
  'canceled',
  'unpaid',
  'incomplete',
  'incomplete_expired',
  'paused',
] as const
export type SubscriptionStatus = (typeof SUBSCRIPTION_STATUSES)[number]

/**
 * One row per organization, mirroring what Polar holds.
 *
 * It is a mirror and not a system of record: Polar decides what has been paid for, and every
 * column here is (re)written by the webhook. What the row adds is a local, synchronous answer to
 * "may this workspace do this" — a quota check cannot make a network call to a billing provider
 * on the write path.
 *
 * The three `*_limit*` columns and `quota_overrides` are **ceilings applied on top of the plan
 * catalog**, which is what makes grandfathering an existing customer possible without inventing
 * a plan for them.
 */
export const subscriptions = sqliteTable(
  'subscriptions',
  {
    id: id(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organization.id, { onDelete: 'cascade' }),

    /** Cached tier. The product id below outranks it when the two disagree. */
    plan: text('plan').notNull().default('free'),
    status: text('status').notNull(),

    /** Polar's ids. `provider_customer_id` is created with `external_customer_id = org id`. */
    providerCustomerId: text('provider_customer_id'),
    providerSubscriptionId: text('provider_subscription_id'),
    providerProductId: text('provider_product_id'),

    /** Seats bought. The enforced ceiling is `seat_limit` when that is set. */
    seats: integer('seats').notNull().default(1),

    /** Price as billed: minor units in `currency`, never a float. */
    currency: currencyCode('currency'),
    unitAmountMinor: integer('unit_amount_minor'),
    interval: text('interval'),

    currentPeriodStart: integer('current_period_start', {
      mode: 'timestamp_ms',
    }),
    currentPeriodEnd: integer('current_period_end', { mode: 'timestamp_ms' }),
    cancelAtPeriodEnd: integer('cancel_at_period_end', { mode: 'boolean' })
      .notNull()
      .default(false),
    canceledAt: integer('canceled_at', { mode: 'timestamp_ms' }),
    trialEndsAt: integer('trial_ends_at', { mode: 'timestamp_ms' }),

    /** JSON object of per-metric ceilings that win over the catalog. */
    quotaOverrides: text('quota_overrides'),
    seatLimit: integer('seat_limit'),
    storageLimitBytes: integer('storage_limit_bytes'),

    /**
     * A scheduled change that has been paid for but has not taken effect. Held here rather than
     * applied early, so the entitlement in force is always the one the reader is being billed
     * for right now.
     */
    pendingPlan: text('pending_plan'),
    pendingInterval: text('pending_interval'),
    pendingEffectiveAt: integer('pending_effective_at', {
      mode: 'timestamp_ms',
    }),

    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    // One subscription per workspace: two would make "which plan is this workspace on"
    // ambiguous at exactly the moment money is involved.
    uniqueIndex('subscriptions_organization_id_unique').on(
      table.organizationId,
    ),
    uniqueIndex('subscriptions_provider_subscription_id_unique').on(
      table.providerSubscriptionId,
    ),
    index('subscriptions_provider_customer_id_idx').on(
      table.providerCustomerId,
    ),
    index('subscriptions_status_idx').on(table.status),
    index('subscriptions_current_period_end_idx').on(table.currentPeriodEnd),
    enumCheck('subscriptions_plan_check', table.plan, PLAN_IDS),
    enumCheck(
      'subscriptions_status_check',
      table.status,
      SUBSCRIPTION_STATUSES,
    ),
    enumCheck('subscriptions_pending_plan_check', table.pendingPlan, PLAN_IDS),
    enumCheck(
      'subscriptions_interval_check',
      table.interval,
      BILLING_INTERVALS,
    ),
    enumCheck(
      'subscriptions_pending_interval_check',
      table.pendingInterval,
      BILLING_INTERVALS,
    ),
  ],
)

export type SubscriptionRow = typeof subscriptions.$inferSelect
export type SubscriptionInsert = typeof subscriptions.$inferInsert

/* -------------------------------------------------------------------------- */
/* Catalog — global, no organization_id                                       */
/* -------------------------------------------------------------------------- */

/**
 * The ISO-4217 catalog.
 *
 * Global by design: a currency is a fact about the world, not about a workspace, and two
 * workspaces disagreeing about how many minor-unit digits the yen has is not a state this
 * product can recover from. Writes go through `src/server/catalog` under `requirePermission`,
 * and each one leaves a platform audit row.
 *
 * **`digits` is the scale every amount in that currency is stored at.** The seed rows are
 * derived from `src/lib/money/currencies.ts` rather than transcribed beside it, because the
 * browser needs the same table to parse what a reader typed.
 *
 * `is_disabled` hides a currency from the pickers; there is deliberately no delete. Accounts and
 * historical transactions denominated in a currency must keep formatting correctly forever.
 */
export const currencies = sqliteTable(
  'currencies',
  {
    code: currencyCode('code').primaryKey(),
    name: text('name').notNull(),
    /** Minor-unit digits: 0 (JPY), 2 (most), 3 (KWD, BHD, …). Never assumed. */
    digits: integer('digits').notNull(),
    /** ISO-4217 numeric code, for file formats that carry the number rather than the letters. */
    numericCode: integer('numeric_code'),
    isDisabled: integer('is_disabled', { mode: 'boolean' })
      .notNull()
      .default(false),
  },
  (table) => [
    index('currencies_is_disabled_idx').on(table.isDisabled),
    check(
      'currencies_digits_check',
      sql`${table.digits} >= 0 and ${table.digits} <= 4`,
    ),
    check('currencies_code_check', sql`length(${table.code}) = 3`),
  ],
)

export type CurrencyRow = typeof currencies.$inferSelect

/** Where a stored rate came from, so a bad provider-day is identifiable afterwards. */
export const EXCHANGE_RATE_SOURCES = ['fawaz', 'frankfurter', 'manual'] as const
export type ExchangeRateSource = (typeof EXCHANGE_RATE_SOURCES)[number]

/**
 * One day's rate for one ordered currency pair.
 *
 * The primary key is `(base_code, quote_code, date)` and the value is an integer: see the
 * `rate_e10` note in the file docblock. `date` is a UTC calendar date in `YYYY-MM-DD`, which is
 * also what makes the key sort chronologically as text.
 *
 * A transaction stores the rate it used on its own row, so a report never joins this table to
 * reproduce a historical conversion — this is the catalog a *new* conversion is priced from, and
 * the input to the nightly refresh.
 */
export const exchangeRates = sqliteTable(
  'exchange_rates',
  {
    baseCode: currencyCode('base_code')
      .notNull()
      .references(() => currencies.code),
    quoteCode: currencyCode('quote_code')
      .notNull()
      .references(() => currencies.code),
    /** UTC calendar date, `YYYY-MM-DD`. */
    date: text('date', { length: 10 }).notNull(),
    /** The rate × 10^10, as an integer. Never a float. */
    rateE10: integer('rate_e10').notNull(),
    source: text('source').notNull(),
    fetchedAt: integer('fetched_at', { mode: 'timestamp_ms' }).notNull(),
  },
  (table) => [
    primaryKey({
      name: 'exchange_rates_pk',
      columns: [table.baseCode, table.quoteCode, table.date],
    }),
    // "The most recent rate for this pair" and "every pair I refreshed on this date" are the two
    // queries the nightly job and the converter actually run.
    index('exchange_rates_date_idx').on(table.date),
    index('exchange_rates_quote_code_date_idx').on(table.quoteCode, table.date),
    enumCheck(
      'exchange_rates_source_check',
      table.source,
      EXCHANGE_RATE_SOURCES,
    ),
    check('exchange_rates_rate_e10_check', sql`${table.rateE10} > 0`),
    check('exchange_rates_date_check', sql`length(${table.date}) = 10`),
    check(
      'exchange_rates_pair_check',
      sql`${table.baseCode} <> ${table.quoteCode}`,
    ),
  ],
)

export type ExchangeRateRow = typeof exchangeRates.$inferSelect
