/** A 25-character application-minted id. See the docblock above. */
const id = () => text('id').primaryKey()

/** Epoch milliseconds. Never a SQLite `datetime` string: the two sort differently. */
const createdAt = () =>
  integer('created_at', { mode: 'timestamp_ms' }).notNull()
const updatedAt = () =>
  integer('updated_at', { mode: 'timestamp_ms' }).notNull()

/** An ISO-4217 alphabetic code. Three characters, upper case, always. */
const currencyCode = (name: string) => text(name, { length: 3 })

/**
 * The tenant column.
 *
 * Every tenant-owned table in this file declares it with this helper and nothing else, so
 * "does this table have `organization_id`" is a grep rather than a reading. `onDelete: 'cascade'`
 * means deleting a workspace takes its data with it in one statement; a soft-delete flag would
 * leave rows a tenant-scoped query still has to remember to exclude.
 */
const organizationId = () =>
  text('organization_id')
    .notNull()
    .references(() => organization.id, { onDelete: 'cascade' })

/** A UTC calendar date, `YYYY-MM-DD`. Never an instant, never a local date. */
const calendarDate = (name: string) => text(name, { length: 10 })

/**
 * A `#rrggbb` colour, seven characters including the hash.
 *
 * Stored as text, and stored as the value itself rather than as a reference to a palette entry,
 * for two reasons that are load-bearing rather than stylistic:
 *
 * - **Equality is domain logic.** `cascadeColor` in `src/server/repos/categories.ts` defines "this
 *   child inherits its parent's colour" as `child.color === parent's previous colour`. The
 *   repository compares these values, so re-representing them as palette indices would change what
 *   inheritance means.
 * - **The set is open.** The write schemas accept any well-formed `#rrggbb`, not an enumeration, so
 *   an imported row carries whatever colour it came with. A column that could only hold a palette
 *   index could not store it, and rejecting it would lose data.
 *
 * The accompanying `CHECK` constrains length only, so case is not normalised on the way in and
 * comparisons against a known palette must fold it — see `seriesVarForHex` in
 * `src/components/app/categories/palette.ts`, which is also what lets a stored light-theme hex
 * paint through a themed token instead of directly.
 */
const colorHex = (name: string) => text(name, { length: 7 })

/** A `CHECK` asserting a nullable text column, when present, is exactly `length` characters. */
function fixedLengthCheck(
  constraintName: string,
  column: AnySQLiteColumn,
  length: number,
): ReturnType<typeof check> {
  return check(
    constraintName,
    sql`length(${column}) = ${sql.raw(String(length))}`,
  )
}

/** A `CHECK` asserting a text column, when present, is at most `length` characters. */
function maxLengthCheck(
  constraintName: string,
  column: AnySQLiteColumn,
  length: number,
): ReturnType<typeof check> {
  return check(
    constraintName,
    sql`length(${column}) <= ${sql.raw(String(length))}`,
  )
}

/**
 * A `CHECK` asserting an amount column holds a strictly positive number of minor units.
 *
 * **The sign of a transaction lives in `direction`, never in the amount.** One representation of
 * "spent 20" is the whole point: two representations means every consumer has to normalise, and
 * one of them will forget.
 */
function positiveMinorCheck(
  constraintName: string,
  column: AnySQLiteColumn,
): ReturnType<typeof check> {
  return check(constraintName, sql`${column} > 0`)
}

/** A `CHECK` asserting a counter or an ordering position is not negative. */
function nonNegativeCheck(
  constraintName: string,
  column: AnySQLiteColumn,
): ReturnType<typeof check> {
  return check(constraintName, sql`${column} >= 0`)
}

/**
 * A `CHECK` constraint restricting a column to one tuple of literals.
 *
 * The tuple is the same value the column's TypeScript type is derived from, so adding a variant
 * in one place and forgetting the other is impossible. Values are inlined as SQL string literals
 * rather than bound parameters because a `CHECK` is part of the table definition and cannot carry
 * placeholders; every caller in this file passes a frozen tuple of source literals, never input.
 */
function enumCheck(
  constraintName: string,
  column: AnySQLiteColumn,
  values: ReadonlyArray<string>,
): ReturnType<typeof check> {
  const list: SQL = sql.join(
    values.map((value) => sql.raw(`'${value.replaceAll("'", "''")}'`)),
    sql`, `,
  )
  return check(constraintName, sql`${column} in (${list})`)
}

